export const createDoctorWeeklySchedule = (
  availableDays: ('Mon' | 'Tue' | 'Wed' | 'Thu' | 'Fri' | 'Sat' | 'Sun')[],
  allowsVideo: boolean,
  clinicTiming: string = '09:00 AM - 01:00 PM, 04:30 PM - 07:30 PM',
  videoTiming: string = '05:00 PM - 08:30 PM'
): DaySchedule[] => {
  const allDays: Array<{
    day: 'Monday' | 'Tuesday' | 'Wednesday' | 'Thursday' | 'Friday' | 'Saturday' | 'Sunday';
    shortDay: 'Mon' | 'Tue' | 'Wed' | 'Thu' | 'Fri' | 'Sat' | 'Sun';
  }> = [
    { day: 'Monday', shortDay: 'Mon' },
    { day: 'Tuesday', shortDay: 'Tue' },
    { day: 'Wednesday', shortDay: 'Wed' },
    { day: 'Thursday', shortDay: 'Thu' },
    { day: 'Friday', shortDay: 'Fri' },
    { day: 'Saturday', shortDay: 'Sat' },
    { day: 'Sunday', shortDay: 'Sun' },
  ];

  return allDays.map(({ day, shortDay }) => {
    const isAvail = availableDays.includes(shortDay);
    if (!isAvail) {
      return {
        day,
        shortDay,
        isAvailable: false,
        clinicTiming: 'Doctor Off / Hospital Duty',
        morningSlots: [],
        afternoonSlots: [],
        eveningSlots: [],
        consultationTypes: [],
        notes: 'Doctor is not available on this day. Please pick another active weekday.',
      };
    }

    const consultationTypes: ConsultationType[] = allowsVideo
      ? ['IN_CLINIC', 'VIDEO']
      : ['IN_CLINIC'];

    return {
      day,
      shortDay,
      isAvailable: true,
      clinicTiming,
      videoTiming: allowsVideo ? videoTiming : undefined,
      morningSlots: ['09:00 AM', '09:30 AM', '10:15 AM', '11:00 AM', '11:45 AM'],
      afternoonSlots: ['12:30 PM', '01:15 PM', '02:30 PM', '03:15 PM'],
      eveningSlots: ['04:30 PM', '05:15 PM', '06:00 PM', '06:45 PM', '07:30 PM'],
      consultationTypes,
      notes: allowsVideo
        ? 'Both In-Clinic Visits & Online Video Consultations available.'
        : 'In-Clinic Physical Visits only (Video Consultation not offered).',
    };
  });
};

